// One hand-rolled 24×24 stroke icon per Settings tab, in the house SVG idiom
// (fill=none, stroke=currentColor, width 2, round caps/joins). They inherit `currentColor`, so the
// rail's active/inactive text colour drives them for free — no per-state variants. The caller sizes
// them via className (the rail uses h-4 w-4). No icon library is a dependency (AGENTS.md "lean deps").
//
// To add a tab: add an icon here and reference it from `registry.ts` — nothing else imports these.

import type { ReactNode, SVGProps } from "react";

function Icon({ children, ...props }: SVGProps<SVGSVGElement> & { children: ReactNode }) {
  return (
    <svg
      viewBox="0 0 24 24"
      fill="none"
      stroke="currentColor"
      strokeWidth={2}
      strokeLinecap="round"
      strokeLinejoin="round"
      aria-hidden="true"
      {...props}
    >
      {children}
    </svg>
  );
}

